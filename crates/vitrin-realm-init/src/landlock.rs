//! K12b -- the Landlock ruleset the realm's app inherits (P2.6.3, issue
//! #187).
//!
//! # Where this runs, and why the position is not negotiable
//!
//! Inside [`crate::exec_shim`], on PID 1 of the realm's pid namespace, in a
//! window bounded on both sides:
//!
//! - **after** `PR_SET_NO_NEW_PRIVS` (K10, [`crate::drop_all_capabilities`]),
//!   because `landlock_restrict_self` refuses without it;
//! - **after** `pivot_root` (K8), because every path below is an *in-realm*
//!   absolute path and would otherwise be resolved against the host tree;
//! - **before** K13's `close_range(4, UINT_MAX, CLOSE_RANGE_CLOEXEC)`,
//!   because every rule here is an `O_PATH` descriptor and one left unmarked
//!   is a descriptor the app inherits;
//! - **before** the `chdir` (K14), the argv assembly and the `execve`, each of
//!   which must therefore fall inside the granted set. A ruleset that forgets
//!   `/vitrin/vitrin-shim` does not fail here; it fails at `execve` with `EACCES`,
//!   which is a realm that will not start.
//!
//! Ordinary Rust is allowed (this binary is single-threaded by design -- see
//! `main.rs`'s module docs), so the grant table below is built with `Vec` and
//! `CString` rather than in async-signal-safe primitives. The three syscall
//! wrappers are nonetheless allocation-free, because [`crate::tests`] drives
//! [`add_path_rule`] and [`restrict_self`] from a forked child. [`create_ruleset`]
//! is called from the parent there -- the ledger has to read the rung off the
//! ruleset, and a child's recording dies with the child -- and keeps the
//! property anyway, because the shipped path calls all three in sequence.
//!
//! # Raw syscalls, and no `landlock` crate
//!
//! `Cargo.toml` records a **one-dependency budget** for this binary against
//! plan risk R7, and records that `rustix` was evaluated and declined. The
//! same reasoning governs here and more strongly: this is the process that
//! *builds* a realm's confinement, so every crate it links is a crate that
//! can weaken one. Three syscall numbers and two `#[repr(C)]` structs is the
//! whole surface, and `spawn/isolation.rs` already spells 444 by hand for the
//! ABI probe -- this file follows that precedent rather than inventing a
//! second one.
//!
//! # What a "rung" is, mechanically
//!
//! A Landlock ABI rung is **which bits are legal in `handled_access_fs`**
//! (plus, at rung 6, in `scoped`). The kernel refuses `EINVAL` at ruleset
//! creation for a bit above its own ABI, which has two consequences this
//! module is built on:
//!
//! 1. There is a **declared floor**, not a degradation ladder (owner's
//!    decision, 2026-08-15; [`vitrin_realm_init::LANDLOCK_MIN_ABI`]). A shipped
//!    session asks for the highest rung this build and this kernel agree on,
//!    and a kernel below the floor is **refused** -- by the core before any
//!    realm is spawned, and again by [`apply_with`] if it ever gets that far.
//!    The one-rung-at-a-time descent still exists in [`create_ruleset`] and now
//!    bottoms out at the floor; what comes back is still what the kernel
//!    granted, never what was asked for, and the core still warns when the two
//!    differ. **The floor narrowed #187 rather than completing it**; P2.6.3 was
//!    accepted on 2026-08-19 (Correction 7, D-044), and PRD §20's "coverage is
//!    kernel-dependent" caveat is answered for the five kernels #281 booted
//!    (`docs/book/src/isolation-kernels.md`) and for no others. The multi-rung table
//!    that *did* get built (`docs/book/src/isolation-matrix.md`, `cargo xtask
//!    isolation-matrix`) is generated by **parsing this file** -- the bit
//!    constants, the base mask, and each `if rung >= N` guard in
//!    [`handled_access_fs`] -- so moving a right to another rung here makes
//!    the checked-in page stale and CI red. It measures no kernel.
//!    `docs/plan/02-phase-2-semantic-epochs.md` carries both corrections.
//! 2. The **cap reproduces exactly what this build asks for on an ABI-N
//!    kernel** -- which is not the same sentence as "reproduces an ABI-N
//!    kernel", and the difference is three rungs wide. Requesting rung N on a
//!    kernel that supports M > N uses rung N's `handled_access_fs`, so each
//!    rung's absence is *measurable* instead of prose -- **for the rungs that
//!    move that mask**: 1, 2, 3, 5 and 9 move `handled_access_fs`, and 6
//!    moves `scoped`. Rungs **4, 7 and 8 do not**. Rung 4 buys
//!    `handled_access_net`, which this module deliberately leaves zero (see
//!    "What this ruleset does not do"); rungs 7 and 8 buy
//!    `landlock_restrict_self` *flags*, which [`restrict_self_flags`] passes
//!    as zero in every shipped run (the one way to move it is the
//!    [`vitrin_realm_init::LANDLOCK_AUDIT_ENV`] diagnostic, which changes what
//!    the kernel logs and nothing about what it permits). Nothing this build
//!    asks for changes across those rungs, so
//!    there is nothing for a cap to take away, and the enforced domain --
//!    `handled_access_fs`, `scoped` and the flags word together -- is
//!    **byte-identical at rungs 3 and 4** and **byte-identical at rungs 6, 7
//!    and 8**. Nine rung numbers, six distinct domains. `--landlock=abi:4`
//!    and `--landlock=abi:7` are still accepted and still journal a distinct
//!    `applied_profile`, so that string names *which rung was obtained* and
//!    never *how much confinement*; every published statement of the ladder
//!    carries the exception.
//!
//! **What rung N is not, is uniformly weaker than rung N+1.** An earlier
//! draft of this module said "the cap can only weaken"; that is false, and
//! [`REFER`] is why. A domain denies reparenting whenever its ruleset does
//! not *handle* `REFER`, so rung 1 forbids a cross-directory `rename(2)`
//! inside the realm's own writable storage and rung 2 permits it. Measured
//! here (kernel `7.1.8-arch1-3`, ABI 9, 2026-08-14): rung 1 answers `EXDEV`,
//! rungs 2..=9 succeed, and a same-directory rename succeeds at every rung.
//! **Only the first two of those rungs are re-taken by a test.**
//! `rung_one_forbids_reparenting_that_the_rung_above_permits` enters a domain
//! at rungs 1 and 2 and at no other -- it declares that in `BEHAVIOURAL_RUNGS`
//! and asserts it against the rungs it actually entered -- so rungs 3..=9
//! above, and the same-directory result at any rung but 1, are a **hand run on
//! that one date**: checked by a reader, and by nothing in CI. Do not read the
//! range as coverage; `docs/book/src/limits.md` and
//! `docs/book/src/isolation-matrix.md` draw the same line, which is why they
//! can also say no test enters a domain at rung 4 or rung 5 without
//! contradicting this paragraph.
//! The cap is a **dial**, not a one-way weakening, and every published
//! statement of it says so.
//!
//! # The consequence nobody grants their way out of: **no mounts, ever**
//!
//! A Landlock domain denies **every** mount-topology change to the sandboxed
//! process and all its descendants, unconditionally. It is not an access
//! right, so it is not in any rule and no grant enables it. Measured on this
//! box rather than read: with **all** rights granted on `/`, a process that
//! creates its own user + mount namespace and then calls `mount(NULL, "/",
//! NULL, MS_REC|MS_PRIVATE, NULL)` gets `EPERM`; without the domain, the same
//! sequence returns 0.
//!
//! So an app inside a realm cannot run a **nested sandbox that mounts**.
//! `bubblewrap` is the one that matters in practice -- measured: `bwrap
//! --unshare-all ...` fails at its first `mount` with "Failed to make /
//! slave: Operation not permitted" under any domain, and succeeds without
//! one. GTK's `glycin` image loaders spawn exactly that, so a GTK app that
//! must decode an SVG icon inside a realm decodes it **unsandboxed**. This is
//! published in `docs/book/src/limits.md`; it is a property of the mechanism,
//! not of the grant table below, and widening the grants cannot touch it.
//!
//! **What the app *receives* is decided one step earlier, and not here.**
//! `main.rs`'s K9b (`deny_nested_user_namespaces`) writes `0` to the realm's
//! own `/proc/sys/user/max_user_namespaces`, so a nested sandbox is refused at
//! `unshare(CLONE_NEWUSER)` instead of at the `mount` this file's domain would
//! have refused. That takes nothing away -- a nested namespace under this
//! domain could not have mounted anything -- and it is what turns the paragraph
//! above from "the app aborts" into "the app degrades". Do not reason about
//! the abort from this file alone; the two steps are load-bearing together.
//!
//! **"Widening cannot touch it" is measured, not reasoned**, because it is the
//! first thing anyone reading this file will want to try. A process holding a
//! domain that handles the whole rung-9 mask and grants *every one of those
//! rights on `/`* -- strictly more than [`grants`] can ever produce, and more
//! than the realm-root grant #187 declined -- fails the identical `glycin`
//! decode with the identical message (Arch, kernel `7.1.8-arch1-3`, ABI 9,
//! 2026-08-14). The one filesystem denial this ruleset does contribute on that
//! path is `openat("/", O_DIRECTORY)` -> `EACCES`, which `glycin` logs and
//! continues past; it is not the abort. See [`grants`] for why that one is
//! refused anyway.
//!
//! What it costs is not hypothetical: until 2026-08-15 it took
//! `test_real_actuation.py` -- **`run.sh`'s named M1.4 actuation gate
//! (#108)** -- plus `test_real_gtk.py` and `test_real_firefox.py` **red at the
//! shipped default**. K9b closed that (all three re-measured green at the
//! shipped default, same box, 2026-08-15) by changing *which* error a nested
//! sandbox receives, not by restoring the mount. What survives, and what the
//! limits page still publishes under
//! `landlock-breaks-nested-image-sandboxes`, is that image decoding inside a
//! realm on such a host runs with **no sandbox around it**. No gate here is
//! skipped or exempted.
//!
//! # What this ruleset does not do
//!
//! It requests **no `handled_access_net`**. Rungs 4 and 10 scope TCP and UDP
//! bind/connect by port; the realm's own network namespace (P2.6.2, and
//! P2.7.1 after it) carries that claim structurally and far more completely,
//! since it covers UDP and raw sockets too. Naming the field here would imply
//! this ruleset is what confines a realm's network, and it is not.

