/// The cumulative `handled_access_fs` mask at one rung.
///
/// Every value here was verified empirically against this kernel rather than
/// recalled: `0x1fff`, `0x3fff`, `0x7fff`, `0xffff`, `0x1ffff` accepted;
/// `0x3ffff` (rung 10's) refused `EINVAL`.
///
/// **Four of the nine rungs do not move it at all** (4, 6, 7 and 8), and the
/// flatness is the honest picture of how much of the ABI ladder this ruleset
/// consumes -- it is shown rather than hidden. That sentence is **computed**,
/// not typed: `cargo xtask isolation-matrix` parses the ladder out of the
/// function below and refuses to emit unless this comment carries the count it
/// derives. The form it replaced was hand-written and had drifted -- it
/// counted ABI 10, a clamp row above this build's ceiling that never reaches
/// this function, as one of the rungs.
fn handled_access_fs(rung: u32) -> u64 {
    let mut mask = EXECUTE
        | WRITE_FILE
        | READ_FILE
        | READ_DIR
        | REMOVE_DIR
        | REMOVE_FILE
        | MAKE_CHAR
        | MAKE_DIR
        | MAKE_REG
        | MAKE_SOCK
        | MAKE_FIFO
        | MAKE_BLOCK
        | MAKE_SYM;
    if rung >= 2 {
        mask |= REFER;
    }
    if rung >= 3 {
        mask |= TRUNCATE;
    }
    if rung >= 5 {
        mask |= IOCTL_DEV;
    }
    if rung >= 9 {
        mask |= RESOLVE_UNIX;
    }
    mask
}

/// [`handled_access_fs`], for the table test. The mask is what a rung *is*,
/// so it is pinned rather than left to be re-derived from this file.
#[cfg(test)]
pub fn handled_access_fs_for_test(rung: u32) -> u64 {
    handled_access_fs(rung)
}

/// [`scoped`], for the same reason.
#[cfg(test)]
pub fn scoped_for_test(rung: u32) -> u64 {
    scoped(rung)
}

/// Rung 6's `scoped` mask. Zero below it, because a nonzero `scoped` on a
/// kernel whose `struct landlock_ruleset_attr` is shorter is `E2BIG`.
fn scoped(rung: u32) -> u64 {
    if rung >= 6 {
        SCOPE_ABSTRACT_UNIX_SOCKET | SCOPE_SIGNAL
    } else {
        0
    }
}

/// What was actually enforced.
///
/// [`vitrin_realm_init::plan_rung`] decides what to *ask* for; this is what
/// came back.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Enforced {
    /// The rung the ruleset was built at. `0` only when the session asked for
    /// no ruleset at all.
    pub rung: u32,
    /// What this kernel reported for its own ABI, so `rung < kernel_abi` is
    /// visible in one journal entry.
    ///
    /// `0` means **not measured**, which happens on exactly one path: a
    /// session that asked for no ruleset, where [`apply`] returns before
    /// issuing any syscall at all. It is not an ABI number -- Landlock ABI
    /// versions start at 1 -- and the core journals it as `null` rather than
    /// as a rung.
    pub kernel_abi: u32,
}

