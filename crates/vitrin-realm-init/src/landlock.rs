/// Build, grant and enforce. Returns what was actually enforced.
///
/// **Fails closed.** A session that asked for a ruleset and cannot have one
/// is a refused spawn, never a realm that starts without it: the whole point
/// of D-020(6)'s floor is that confinement does not degrade silently. The one
/// legal way to get no ruleset is to ask for none.
pub fn apply(config: &Config) -> Result<Enforced, Fail> {
    apply_with(config, kernel_abi)
}

/// [`apply`], with the ABI query injected.
///
/// The seam exists for exactly one assertion, and it is not a convenience:
/// `Off` must short-circuit **before any syscall**, and on a kernel that has
/// Landlock -- every kernel this repo's tests run on -- a test cannot tell
/// "the query was skipped" from "the query succeeded". Passing the query in
/// lets the test hand over a probe that *records being called* and answers
/// `ENOSYS`, so moving the short-circuit back below the query turns the test
/// red instead of leaving it green on the only machines available.
///
/// # The bug this shape fixes
///
/// The first draft queried the ABI before reading the request. A kernel with
/// no Landlock at all answers `ENOSYS`, `kernel_abi` turns that into a
/// [`Fail`], and **every realm spawn died -- including the ones that had
/// asked for no ruleset**. `spawn/isolation.rs`'s `admit` deliberately waives
/// the floor for `--landlock=off`, so the flag existed, was documented as the
/// answer for such a machine, and did not work; the operator's only remaining
/// move was `--isolation=off`, which drops the namespaces too. The refusal
/// text on that path also named a ruleset nobody had asked for.
pub(crate) fn apply_with(
    config: &Config,
    kernel_abi: impl FnOnce() -> Result<u32, Fail>,
) -> Result<Enforced, Fail> {
    // **First, and above the syscall.** See this function's docs.
    if config.landlock == LandlockRequest::Off {
        return Ok(Enforced {
            rung: 0,
            // Not measured rather than zero-as-a-rung: nothing asked the
            // kernel anything, and the core renders this as `null`.
            kernel_abi: 0,
        });
    }
    let kernel_abi = kernel_abi()?;
    // **The floor, checked here as well as in the core.** The core's
    // `spawn::isolation::admit` refuses such a machine before any realm is
    // spawned, so reaching this arm means the core's probe and the helper's
    // disagreed -- a substituted core, or a kernel whose LSM set changed under
    // a running session. Refused rather than degraded, because a helper that
    // quietly built a rung-4 domain would be the one outcome D-020(6) forbids:
    // the realm would be confined less than the session's own journal says.
    if kernel_abi < vitrin_realm_init::LANDLOCK_MIN_ABI {
        eprintln!(
            "vitrin-realm-init: this kernel reports Landlock ABI {kernel_abi} and this build's \
             floor is ABI {}. Refusing the realm rather than enforcing a weaker domain than the \
             session claims. `--landlock=off` starts realms with NO ruleset and is not a remedy \
             for a kernel that could be upgraded.",
            vitrin_realm_init::LANDLOCK_MIN_ABI
        );
        return Err(Fail::with(Stage::Landlock, libc::EPROTO));
    }
    // [`vitrin_realm_init::Plan::clamped_by_build`] is not sent as a third
    // number, and does not need to be: the **core** recomputes the same plan
    // from `(kernel_abi, request)` through the same pure function, which is
    // what lets it tell a ladder fallback from an operator's cap and journal
    // the clamp. Sending a boolean the core can derive would be a second
    // opinion about one session.
    let plan = plan_rung(kernel_abi, config.landlock);
    let ruleset = create_ruleset(plan.rung)?;
    let rung = ruleset.rung();

    // The **diagnostic** flags word (see [`restrict_self_flags`]). Read from
    // this process's own environment, which the core populated from nothing
    // and then added exactly this one name to, and only when its own
    // environment carried it.
    //
    // Announced on stderr -- the realm's own log file -- in both directions,
    // because the failure mode of a diagnostic is silence: a measurement run
    // that quietly did not turn the log on reads exactly like a run that found
    // no denials. The second arm is the one that matters on a kernel below ABI
    // 7, where the bit is `EINVAL` rather than ignored, so the helper drops it
    // and says so instead of refusing the realm over an instrument.
    let audit = vitrin_realm_init::landlock_audit_requested(
        std::env::var(vitrin_realm_init::LANDLOCK_AUDIT_ENV)
            .ok()
            .as_deref(),
    );
    let flags = restrict_self_flags(rung, audit);
    if flags != 0 {
        eprintln!(
            "vitrin-realm-init: LANDLOCK AUDIT DIAGNOSTIC ON \
             ({}=1): landlock_restrict_self flags=0x{flags:x} \
             (LANDLOCK_RESTRICT_SELF_LOG_NEW_EXEC_ON) at rung {rung}. \
             The kernel will log this realm's denials AFTER the shim's execve. \
             The ruleset itself is unchanged.",
            vitrin_realm_init::LANDLOCK_AUDIT_ENV
        );
    } else if audit {
        eprintln!(
            "vitrin-realm-init: {}=1 asked for the Landlock audit diagnostic, \
             but this realm obtained rung {rung} and the log flags need rung \
             {LOG_FLAGS_RUNG}. Enforcing with flags=0; no post-execve denial \
             will be logged.",
            vitrin_realm_init::LANDLOCK_AUDIT_ENV
        );
    }

    let handled = handled_access_fs(rung);
    let result = (|| {
        for entry in grants(config)? {
            // Masked by the rung, because a rule naming an unhandled bit is
            // `EINVAL` -- which is also what makes a capped session behave
            // exactly like the older kernel it is imitating rather than
            // erroring differently.
            match add_path_rule(ruleset.fd(), &entry.path, entry.rights & handled) {
                Ok(()) => {}
                Err(fail) if !entry.required && fail.errno == libc::ENOENT => {}
                Err(fail) => return Err(fail),
            }
        }
        enter_domain(&ruleset, flags)
    })();
    // The descriptor closes with `ruleset` when this function returns, on both
    // paths: after `restrict_self` the domain is enforced and the descriptor is
    // inert, and on the error path the caller is about to `_exit`.
    result?;

    Ok(Enforced { rung, kernel_abi })
}
