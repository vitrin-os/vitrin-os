/// `landlock_create_ruleset(2)`, `landlock_add_rule(2)`,
/// `landlock_restrict_self(2)`.
///
/// Uniform across architectures: the Landlock calls arrived in 5.13 through
/// the *generic* syscall table, unlike `seccomp`'s per-architecture
/// numbering. On an architecture without them the call answers `ENOSYS`,
/// which this module reports as a refusal rather than treating as "no
/// confinement needed".
const SYS_LANDLOCK_CREATE_RULESET: libc::c_long = 444;
const SYS_LANDLOCK_ADD_RULE: libc::c_long = 445;
const SYS_LANDLOCK_RESTRICT_SELF: libc::c_long = 446;

/// With a null attribute and a zero size this flag turns the create call into
/// a pure ABI query that creates nothing.
const LANDLOCK_CREATE_RULESET_VERSION: libc::c_uint = 1;

/// `LANDLOCK_RULE_PATH_BENEATH`. The only rule type this build adds.
const LANDLOCK_RULE_PATH_BENEATH: libc::c_uint = 1;

// The filesystem access rights, by the ABI rung that introduced them.
// Rung 1:
const EXECUTE: u64 = 1 << 0;
const WRITE_FILE: u64 = 1 << 1;
const READ_FILE: u64 = 1 << 2;
const READ_DIR: u64 = 1 << 3;
const REMOVE_DIR: u64 = 1 << 4;
const REMOVE_FILE: u64 = 1 << 5;
const MAKE_CHAR: u64 = 1 << 6;
const MAKE_DIR: u64 = 1 << 7;
const MAKE_REG: u64 = 1 << 8;
const MAKE_SOCK: u64 = 1 << 9;
const MAKE_FIFO: u64 = 1 << 10;
const MAKE_BLOCK: u64 = 1 << 11;
const MAKE_SYM: u64 = 1 << 12;
/// Rung 2. **Inverted, and the one rung whose absence is not a weakening.**
/// `REFER` is denied by *any* ruleset that does not handle it, so an ABI-1
/// domain is stricter about reparenting, not weaker: measured here, a
/// cross-directory `rename(2)` inside a fully granted hierarchy answers
/// `EXDEV` at rung 1 and succeeds from rung 2 up. Handling it is what lets
/// the realm rename across directories inside its own storage -- which is how
/// GTK and Firefox write files (atomic rename-into-place).
///
/// This is the whole reason the published invariant is "the cap reproduces an
/// ABI-N kernel", never "the cap only weakens".
const REFER: u64 = 1 << 13;
/// Rung 3. Without it a payload that cannot *write* a file can still destroy
/// it: `truncate(2)`, `creat(2)` and `O_TRUNC` are ungated below this rung.
const TRUNCATE: u64 = 1 << 14;
/// Rung 5. Gates `ioctl(2)` on opened character and block devices. A
/// documented set of generic commands (`FIOCLEX`, `FIONBIO`, `FIONREAD`, ...)
/// stays invokable regardless.
const IOCTL_DEV: u64 = 1 << 15;
/// Rung 9. Restricts `connect(2)` and addressed `sendmsg(2)` to **pathname**
/// UNIX sockets. Handling it without granting it on the shim's Wayland socket
/// path would stop the app reaching its display server, and the failure mode
/// is a black screen rather than a log line -- see [`grants`].
const RESOLVE_UNIX: u64 = 1 << 16;

/// Rung 6's `scoped` field: the domain cannot connect to an abstract UNIX
/// socket created outside it, and cannot signal a process outside it.
///
/// Both are also carried structurally by P2.6.2's namespaces -- abstract
/// sockets are per-netns, and the pid namespace already denies signalling
/// outward -- so this rung is defence in depth rather than the mechanism
/// behind either published claim.
const SCOPE_ABSTRACT_UNIX_SOCKET: u64 = 1 << 0;
const SCOPE_SIGNAL: u64 = 1 << 1;

/// `LANDLOCK_RESTRICT_SELF_LOG_NEW_EXEC_ON`, rung 7's second flag bit.
///
/// The kernel's default is to audit a domain's denials for the **current**
/// execution only and to fall silent across `execve`. This bit keeps the log
/// on afterwards, which is the only side of the `execve` where a realm's app
/// runs.
const LOG_NEW_EXEC_ON: libc::c_uint = 1 << 1;

/// The rung that first accepts [`LOG_NEW_EXEC_ON`]. Below it the flag is not
/// "ignored", it is `EINVAL` -- which would turn a diagnostic into a realm
/// that will not start.
const LOG_FLAGS_RUNG: u32 = 7;

/// The `flags` argument of `landlock_restrict_self`, which is **zero in every
/// shipped run**.
///
/// Rungs 7 and 8 buy flags here rather than mask bits: 7 is audit-log control
/// (`LOG_SAME_EXEC_OFF`, `LOG_NEW_EXEC_ON`, `LOG_SUBDOMAINS_OFF`) and 8 is
/// `TSYNC`. Neither is requested by a shipped session, and each absence has a
/// reason rather than being an oversight:
///
/// - **`TSYNC` (rung 8)** applies the domain to every thread of the calling
///   process. This binary is single-threaded by design (`main.rs` module
///   docs) and the ruleset is enforced on the one thread that then `execve`s,
///   so the helper's shape already carries what `TSYNC` would buy.
/// - **The log flags (rung 7)** are an observability lever, not a
///   confinement one; **no published claim depends on them**.
///   `LOG_NEW_EXEC_ON` is what makes the app's post-`execve` denials visible
///   to audit, which is the input P2.6.9's measured read/write set needs.
///   Since it is pure observability it is now reachable -- but only through
///   [`vitrin_realm_init::LANDLOCK_AUDIT_ENV`], a diagnostic the core forwards
///   only when its own environment carries it, never from `realm.toml`, never
///   from a command line, and never by default.
///
/// **What that costs the published ladder, stated rather than buried.** The
/// pages that say the enforced domain is byte-identical at rungs 6, 7 and 8
/// are describing the flags word being zero, which is true of every run that
/// does not set the diagnostic. Under the diagnostic, rung 7 and rung 6 differ
/// by exactly this bit -- and the difference is in what the *kernel logs*, not
/// in what it permits, so no confinement claim moves either way.
///
/// Because both are flags rather than mask bits, **their absence cannot be
/// simulated by the rung cap**: there is nothing to remove from a request that
/// never asked. Those two rungs are therefore prose-backed, as rung 4 is for
/// the same reason on the network side, and `docs/book/src/limits.md` says so
/// in the bullet that also states the byte-identical domains at 3/4 and at
/// 6/7/8. Since 2026-08-15 there **is** a generated ladder table --
/// `docs/book/src/isolation-matrix.md`, emitted by `cargo xtask
/// isolation-matrix` and held by CI -- and it renders these two rungs as
/// "capping simulates it: **no**" from this very function's shape. What that
/// table is *not* is a per-kernel measurement (see
/// `docs/plan/02-phase-2-semantic-epochs.md`, "P2.6.3, corrected",
/// Correction 5): it parses this file rather than probing a machine, so "the
/// published ladder" is now generated and gated, while the *values* behind each
/// rung's behaviour were recorded on one box on one date -- the tests that take
/// them run here and on the CI runner, whose job declares
/// `VITRIN_REQUIRE_LANDLOCK_ABI=7` so a skip is a panic, and on no third
/// machine.
fn restrict_self_flags(rung: u32, audit: bool) -> libc::c_uint {
    if audit && rung >= LOG_FLAGS_RUNG {
        LOG_NEW_EXEC_ON
    } else {
        0
    }
}

/// [`restrict_self_flags`], for the table test.
#[cfg(test)]
pub fn restrict_self_flags_for_test(rung: u32, audit: bool) -> libc::c_uint {
    restrict_self_flags(rung, audit)
}

/// `struct landlock_ruleset_attr`, as of the ABI this build knows.
///
/// Three fields, and the size passed to the kernel is **this build's own
/// `size_of`**, never a literal: the struct grows between ABI versions (rung
/// 10 adds three more `__u64`s). A smaller size than the running kernel's is
/// zero-filled by `copy_struct_from_user`; a larger one is accepted only if
/// the trailing bytes are zero, which is why [`create_ruleset`] treats
/// `E2BIG` as a rung to step down from rather than a hard failure.
#[repr(C)]
#[derive(Default)]
struct RulesetAttr {
    handled_access_fs: u64,
    handled_access_net: u64,
    scoped: u64,
}

/// `struct landlock_path_beneath_attr`, which the kernel declares
/// **`__attribute__((packed))`** -- 12 bytes, not 16.
#[repr(C, packed)]
struct PathBeneathAttr {
    allowed_access: u64,
    parent_fd: i32,
}

