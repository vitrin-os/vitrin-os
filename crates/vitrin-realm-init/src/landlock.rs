/// Read and list a hierarchy, with **no** right to execute anything in it.
const READ_ANY: u64 = READ_FILE | READ_DIR;

/// Read, list and execute: a hierarchy the realm runs code out of.
const READ_EXEC: u64 = READ_FILE | READ_DIR | EXECUTE;

/// Read and execute a **regular file**, and the missing bit is load-bearing.
///
/// `LANDLOCK_ACCESS_FS_READ_DIR` on a regular file is not an unused right, it
/// is an **`EINVAL` from `landlock_add_rule`** -- measured on this box (ABI 9,
/// 2026-08-14). Every rule that may name a file is `required`, and [`apply`]
/// fails closed, so one such rule takes the whole realm down at the shipped
/// default. `main.rs`'s `a_bind_naming_a_file_gets_rights_the_kernel_accepts`
/// re-measures both halves on every run.
const READ_EXEC_FILE: u64 = READ_FILE | EXECUTE;

/// Everything a realm may do inside a hierarchy it owns.
///
/// **`MAKE_CHAR` and `MAKE_BLOCK` are deliberately absent.** A realm has no
/// business minting device nodes; it also holds no `CAP_MKNOD`, so the
/// syscall would fail anyway -- stating it as a rule turns a side effect of
/// the credential drop into a property of the ruleset, which survives a
/// future tier that hands the realm more capability.
///
/// `RESOLVE_UNIX` travels with every writable hierarchy because a socket the
/// realm creates for itself must stay connectable to it: the shim's
/// `wayland-0`, the reserved accessibility-bus path, and whatever an app
/// binds in its own `/tmp`.
const WRITE_TREE: u64 = READ_FILE
    | READ_DIR
    | WRITE_FILE
    | TRUNCATE
    | REFER
    | REMOVE_DIR
    | REMOVE_FILE
    | MAKE_DIR
    | MAKE_REG
    | MAKE_SOCK
    | MAKE_FIFO
    | MAKE_SYM
    | RESOLVE_UNIX;

/// One granted hierarchy.
struct Grant {
    path: CString,
    rights: u64,
    /// A path that must exist. Everything the **core** named in the config is
    /// required, because the core bound it; only the host-shape-dependent
    /// `/bin`-class compatibility names are optional, since a merged-`/usr`
    /// machine and a split-`/usr` one disagree about which exist.
    required: bool,
}

fn grant(path: &str, rights: u64, required: bool) -> Result<Grant, Fail> {
    Ok(Grant {
        path: CString::new(path).map_err(|_| Fail::with(Stage::Landlock, libc::EINVAL))?,
        rights,
        required,
    })
}

/// **An enumerated read set, with a narrower execute half inside it** (issue
/// #187).
///
/// Every right this ruleset grants is named against one hierarchy. There is no
/// rule on the realm root, which is what makes a path the mount table happened
/// to leave reachable -- `/`, `/run`, `/vitrin`, the `$HOME` stub a bind target
/// needed -- answer `EACCES` rather than opening.
///
/// # A broad read grant at `/` was tried, measured, and reverted
///
/// It is the obvious widening, so the result is recorded here rather than left
/// to be rediscovered. Replacing this enumeration with a single
/// `READ_FILE|READ_DIR` rule on `/`:
///
/// - **takes #186's shipped acceptance gate red.** A `READ_DIR` rule on `/`
///   covers every directory beneath it, so `test_real_confinement.py`'s
///   `/vitrin` denial and its `$HOME` canary both fail -- measured 2026-08-15,
///   two `AssertionError: 'ok' != 'fail'`.
/// - **buys no app compatibility at all**, which is the half that decides it.
///   The three real-app gates that were red at the shipped default until
///   2026-08-15 were red for a reason no grant reaches: a Landlock domain
///   refuses `mount(2)` unconditionally, `bwrap` died at its first mount, and
///   GTK's image loader aborted. Measured with the broad grant in place: the
///   same abort. Measured with **every rung-9 right granted on `/`** --
///   strictly more than either shape can produce: the same abort. What
///   repaired them was `main.rs`'s K9b, which is not a grant and is not in
///   this file. See this module's header and
///   `docs/book/src/limits.md`'s `landlock-breaks-nested-image-sandboxes`.
///
/// So the enumeration is kept, and what it is worth is stated exactly rather
/// than flatteringly: measured against `--landlock=off` it denies a handful of
/// **empty scaffolding directories** the realm's own mount table had to mint to
/// hold a bind target, plus `execve` anywhere under `/etc`. It denies no path
/// that carries data, because the mount table puts host content nowhere but at
/// a bind target and every bind target is granted. `docs/book/src/limits.md`
/// publishes that measurement with the same emphasis.
///
/// # The rule the exec grants follow
///
/// **Landlock's `EXECUTE` grant is exactly the mount table's `noexec` map, less
/// `/etc`.** Where `build_mount_table` permits execution, so does this --
/// `/usr`, the `/bin`-class compatibility names, the shim binary, the app's own
/// directory, the operator's `binds`, and `/tmp` (whose mount is deliberately
/// not `noexec`; see `build_mount_table`). Where the mount forbids it
/// (`/run/vitrin`, `/vitrin/home`, `/dev/shm`, `/proc`, `/sys`, `/dev`),
/// neither does this, so an argued mount flag is not quietly re-decided here.
///
/// `/etc` is the one place the two maps differ, deliberately: it is bound
/// `MS_RDONLY|MS_NOSUID|MS_NODEV` with **no** `noexec`, so the mount permits
/// execution there and only this ruleset refuses it. That single denial is what
/// this layer buys over the mount namespace on the execute axis, and adding
/// `/etc` to the execute set would give it away. **No test in this repository
/// measures it yet** -- said plainly rather than left implied, because an
/// unmeasured denial is prose.
///
/// # Each rule is a complete description of its own hierarchy
///
/// Landlock resolves an access by walking from the file up to the root and
/// clearing the requested rights against every rule it passes, so a file's
/// effective rights are the **union** of every matching ancestor's. With no
/// rule at the root, each row below is the whole of what its hierarchy carries
/// -- `/usr` says `READ_FILE|READ_DIR|EXECUTE`, and a path under it gets
/// exactly that.
///
/// Two rows are a **file** rather than a hierarchy -- the shim binary, and any
/// `binds` entry naming one -- and they carry [`READ_EXEC_FILE`], because
/// `READ_DIR` on a regular file is refused by `landlock_add_rule` outright.
/// [`crate::bind_is_file`] is the one predicate that decides which kind a
/// `binds` entry is, shared with the mount table so the two cannot disagree
/// about what they built.
///
/// # `WRITE_FILE` on the whole of `/proc`, and why it cannot be narrower
///
/// `/proc` carries `WRITE_FILE` -- the right to write *through* an existing
/// file, with no `TRUNCATE`, no `MAKE_*`, no `REMOVE_*` and no `REFER`, so
/// nothing there can be created, deleted, renamed or emptied. The rule is on
/// the hierarchy root, which is broader than the paths any measured app
/// actually writes, and the reason is a property of Landlock rather than a
/// convenience:
///
/// - **A path rule is an `O_PATH` descriptor on one inode.** There is no glob,
///   no pattern and no late binding. To express "each process's own
///   `/proc/<pid>` and nothing else" this function would have to know the pids
///   of processes that do not exist yet -- the ruleset is built and enforced
///   *before* the shim's `execve`, and the app is a later child with a pid this
///   process never sees.
/// - **`/proc/self` is a symlink and `O_PATH` follows it.** A rule opened on
///   `/proc/self` here resolves to `/proc/1`, the helper's own directory, which
///   is precisely the one directory the app is not.
///
/// What the acceptance set actually writes there, measured by tracing the three
/// real-app gates inside a realm at `--landlock=off` (`strace -f -e
/// trace=%file`, 2026-08-14): `/proc/self/oom_score_adj` and
/// `/proc/self/coredump_filter`. Both are per-process knobs on the writer's own
/// task. Nothing in the acceptance set writes `/proc/sys/*` or another task's
/// entry.
///
/// What the breadth costs, stated rather than implied: the realm may write any
/// procfs file its **credentials** already permit -- and it has zero
/// capabilities, an identity uid map and its own pid namespace with a fresh
/// procfs, so that is its own tasks' knobs. `/proc/sys/*` is root-owned and
/// stays refused by DAC. The residual is real but it is bounded by the
/// credential drop, not by this rule, and a future tier that hands a realm more
/// capability must revisit this line rather than inherit it.
///
/// # `IOCTL_DEV`, and what rung 5 does *not* buy
///
/// It is granted on exactly two hierarchies: the **render nodes**, because an
/// app that cannot `ioctl` its render node cannot render at all, and
/// **`/dev/pts`**, because terminal `ioctl`s (`TCGETS`, `TIOCGWINSZ`,
/// `TIOCGPTN`) are how a pty is driven and `/dev/ptmx` is a symlink into it.
/// It is denied on `/dev/null`, `/dev/zero`, `/dev/full`, `/dev/random`,
/// `/dev/urandom`, `/dev/tty` and `/dev/shm`.
///
/// So this rung narrows the realm's device-`ioctl` surface to two paths --
/// and it **does not close the published render-node limit**. `IOCTL_DEV` is
/// one all-or-nothing bit per hierarchy, the app needs the node's `ioctl`s,
/// so the node keeps them. `limits.md`'s "the render node's ioctl surface and
/// the cross-realm GPU-memory side channels it carries are real and
/// unaddressed" survives this rung intact, and that page's ladder bullets say
/// so.
fn grants(config: &Config) -> Result<Vec<Grant>, Fail> {
    let mut out = Vec::new();

    // --- read + execute -----------------------------------------------------
    // `/usr` and the `/bin`-class compatibility names. On a merged-`/usr`
    // host the latter are symlinks into `/usr`, so their `O_PATH` open
    // resolves to a hierarchy `/usr`'s rule already covers and the extra rule
    // is a harmless duplicate; on a split-`/usr` host they are real
    // directories and the rule is the only thing granting them.
    out.push(grant("/usr", READ_EXEC, true)?);
    for name in crate::COMPAT_NAMES {
        out.push(grant(&format!("/{name}"), READ_EXEC, false)?);
    }
    // The shim binary itself -- a FILE bind, so no `READ_DIR` -- and it is the
    // one grant whose absence is a realm that will not start: `execve` is
    // checked against `EXECUTE` here.
    out.push(grant(IN_REALM_SHIM, READ_EXEC_FILE, true)?);
    if let Some(dir) = &config.app_dir {
        out.push(grant(&dir.to_string_lossy(), READ_EXEC, true)?);
    }
    for extra in &config.binds {
        // Operator-declared read-only binds. Their mounts are `RO_BIND` --
        // `MS_RDONLY | MS_NOSUID | MS_NODEV`, with no `noexec` -- so they
        // permit execution and the ruleset mirrors that rather than
        // re-deciding it. A `binds` entry may name a regular file
        // (`examples/realm.toml`: "a regular file or directory"), and the rule
        // for one may not name `READ_DIR`: `landlock_add_rule` refuses it
        // `EINVAL`, every bind is `required`, and `apply` fails closed, so the
        // wrong branch here is every realm on the box refusing to start.
        let rights = if crate::bind_is_file(extra) {
            READ_EXEC_FILE
        } else {
            READ_EXEC
        };
        out.push(grant(&extra.to_string_lossy(), rights, true)?);
    }

    // --- read only, no execute ----------------------------------------------
    // `/etc` is bound with no `noexec`, so the mount permits execution there
    // and withholding `EXECUTE` here is the one filesystem denial this layer
    // contributes that the mount table does not already carry. `/sys` is a
    // fresh, read-only, `noexec` sysfs; the ruleset states the same thing
    // rather than relying on the flag alone.
    out.push(grant("/etc", READ_ANY, true)?);
    out.push(grant("/sys", READ_ANY, true)?);

    // --- the realm's own writable set --------------------------------------
    // **FULL write authority** -- create, delete, rename, truncate -- on
    // exactly the four the mount table publishes as writable
    // (`{/run/vitrin, /vitrin/home, /tmp, /dev/shm}`), and no fifth. `/tmp`
    // additionally carries `EXECUTE`, because its mount deliberately does.
    //
    // This is **not** the whole set of hierarchies carrying a write right, and
    // four published surfaces once said it was. `/proc`, `/dev`, `/dev/pts`
    // and each render node below also get `WRITE_FILE` -- the right to write
    // *through* an existing file or node, with no `TRUNCATE`, no `MAKE_*`, no
    // `REMOVE_*` and no `REFER`, so nothing there can be created, deleted,
    // renamed or emptied. Eight hierarchies carry `WRITE_FILE`; four carry
    // [`WRITE_TREE`]. Any prose that collapses the two is wrong in the
    // flattering direction, which is why the distinction is written here
    // beside the code rather than only on the limits page.
    out.push(grant(IN_REALM_RUNTIME_DIR, WRITE_TREE, true)?);
    out.push(grant(IN_REALM_HOME, WRITE_TREE, true)?);
    out.push(grant("/tmp", WRITE_TREE | EXECUTE, true)?);
    out.push(grant("/dev/shm", WRITE_TREE, true)?);
    // A fresh procfs of the realm's own pid namespace. Writable because real
    // software writes its own `/proc/self/*` (`oom_score_adj`,
    // `coredump_filter`); no `TRUNCATE`, no `MAKE_*`, no `REMOVE_*`, because
    // procfs has no such operations and stating that is free -- and the
    // missing `TRUNCATE` is measurable, which is why it is a gate. See this
    // function's docs for why the rule cannot be narrower than the hierarchy.
    out.push(grant("/proc", READ_ANY | WRITE_FILE, true)?);

    // --- devices ------------------------------------------------------------
    // `/dev` itself is a read-only tmpfs after K4's remount, so `WRITE_FILE`
    // here is the right to write *through* a device node (`/dev/null`), never
    // the right to create one.
    out.push(grant("/dev", READ_ANY | WRITE_FILE, true)?);
    // The pty machinery, including `/dev/ptmx` (a symlink to `pts/ptmx`).
    out.push(grant("/dev/pts", READ_ANY | WRITE_FILE | IOCTL_DEV, true)?);
    // Each bound render node, by name. **No `READ_DIR`**: a render node is a
    // character device, not a directory, and the kernel's rule check refuses
    // any right outside its file set on a non-directory -- measured, `EINVAL`
    // from `landlock_add_rule` on this box (ABI 9, 2026-08-15), which is a
    // refused realm rather than an ignored bit. Same rule as the shim binary
    // and a file `binds` entry; this is the third of the three file rows.
    for node in &config.render_nodes {
        let Some(name) = node.file_name() else {
            return Err(Fail::with(Stage::Landlock, libc::EINVAL));
        };
        out.push(grant(
            &format!("/dev/dri/{}", name.to_string_lossy()),
            READ_FILE | WRITE_FILE | IOCTL_DEV,
            true,
        )?);
    }

    Ok(out)
}

/// [`grants`] flattened to `(path, rights)`, for the file-bind measurement.
///
/// The table is pure -- it issues no syscall but the `stat` behind
/// [`crate::bind_is_file`] -- so a test may build one for any `Config` and
/// then hand each row to the kernel itself, which is what
/// `a_bind_naming_a_file_gets_rights_the_kernel_accepts` does.
#[cfg(test)]
pub fn grants_for_test(config: &Config) -> Result<Vec<(CString, u64)>, Fail> {
    Ok(grants(config)?
        .into_iter()
        .map(|entry| (entry.path, entry.rights))
        .collect())
}

