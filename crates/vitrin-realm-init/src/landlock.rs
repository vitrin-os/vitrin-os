/// The kernel's own ABI number, or the errno that stopped the question being
/// asked.
///
/// Allocation-free.
pub fn kernel_abi() -> Result<u32, Fail> {
    // SAFETY: the null pointer and zero size are exactly what the version
    // query requires; the kernel reads neither.
    let rc = unsafe {
        libc::syscall(
            SYS_LANDLOCK_CREATE_RULESET,
            std::ptr::null::<libc::c_void>(),
            0usize,
            LANDLOCK_CREATE_RULESET_VERSION,
        )
    };
    if rc >= 1 {
        Ok(rc as u32)
    } else if rc == 0 {
        // Documented as impossible -- ABI versions start at 1 -- so a zero is
        // refused rather than quietly treated as rung 0.
        Err(Fail::with(Stage::Landlock, libc::EPROTO))
    } else {
        Err(Fail::at(Stage::Landlock))
    }
}

/// A live Landlock ruleset, together with **the rung the kernel created it
/// at**.
///
/// The rung is the kernel's answer and never the caller's request:
/// [`create_ruleset`] steps down on `EINVAL`/`E2BIG`, and what is recorded here
/// is where that walk stopped. It is the only thing in this tree that builds
/// one **holding a descriptor**, both fields are private, and there is no
/// constructor anywhere that takes a descriptor and a rung as two separate
/// arguments -- so a descriptor cannot be labelled with a rung it was not
/// created at. (The one other constructor, [`Ruleset::unopened`], exists in
/// test builds and holds no descriptor at all.)
///
/// That is the entire point of the type. Entering a domain needs an
/// [`Entering`]; an `Entering` holds one of these; and the ledger reads the
/// rung **off the ruleset it is handed**. Before this type existed, the rung
/// the ledger recorded and the rung the ruleset was built at were two numbers a
/// human kept in step.
pub struct Ruleset {
    fd: RawFd,
    /// The rung `landlock_create_ruleset` accepted -- not the rung asked for.
    rung: u32,
}

impl Ruleset {
    /// The descriptor, for [`add_path_rule`], which does not keep it.
    pub fn fd(&self) -> RawFd {
        self.fd
    }

    /// The rung this ruleset was **created** at.
    pub fn rung(&self) -> u32 {
        self.rung
    }

    /// A rung with **no descriptor**, for the ledger's own non-vacuity proofs.
    ///
    /// `landlock_restrict_self` on `-1` cannot enter a domain at any rung, so
    /// this is safe to hand to a [`RungsEntered`] on a machine that has no
    /// Landlock at all -- which is what both of the ledger's `#[should_panic]`
    /// proofs in `main.rs` need, one per direction:
    /// `a_ledger_asked_for_a_rung_its_row_does_not_name_refuses_to_mint` for
    /// the mint check, and
    /// `a_ledger_that_skipped_a_rung_its_row_declares_fails_on_drop` for the
    /// converse still held in `Drop`. Those two are the only reason this
    /// exists. It is deliberately **not** a way to attach a chosen rung to a
    /// real descriptor: there is no argument here that could carry one.
    #[cfg(test)]
    pub fn unopened(rung: u32) -> Ruleset {
        Ruleset { fd: -1, rung }
    }
}

impl Drop for Ruleset {
    /// Close the descriptor.
    ///
    /// After `landlock_restrict_self` the domain is enforced and the descriptor
    /// is inert, and a measurement body that never got that far is a descriptor
    /// nothing else will close: `main.rs` builds one per measurement, in the
    /// parent, in a loop. `close` is async-signal-safe, so this keeps the
    /// module's allocation-free contract.
    fn drop(&mut self) {
        if self.fd >= 0 {
            // SAFETY: this value's own descriptor, handed out only as a
            // `RawFd` to `add_path_rule` and to the one syscall below.
            unsafe { libc::close(self.fd) };
        }
    }
}

/// Create a ruleset at `rung`, stepping **down** on `EINVAL`/`E2BIG` until the
/// kernel accepts one or the floor is reached.
///
/// # The floor, and why the descent still exists at all
///
/// Since the ABI floor landed (`LANDLOCK_MIN_ABI`, owner's decision 2026-08-15)
/// a shipped session never reaches this function below the floor: [`apply_with`]
/// refuses first, and the core refuses before that. The descent is kept for two
/// narrower reasons, and it bottoms out at `min(rung, LANDLOCK_MIN_ABI)`:
///
/// - a kernel may report ABI N and still refuse rung N's `handled_access_fs`
///   (a build without some right compiled in). One step down is a diagnosis;
///   walking to rung 1 would be the silent degradation the floor exists to end.
/// - `--landlock=abi:N` **is** allowed below the floor, because it is the
///   instrument the per-rung tests drive (`main.rs`'s rung measurements call
///   this directly). A request below the floor is taken literally and is never
///   walked down further -- there is nothing below it worth reaching.
///
/// The fallback is never masked: what comes back is a [`Ruleset`] carrying the
/// rung the kernel accepted, and every caller journals it.
///
/// Allocation-free, so a forked child may call it -- though `main.rs`'s
/// measurement bodies call it in the **parent** and let the forked child
/// inherit the descriptor, because that is what lets the ledger read the rung
/// off the ruleset itself instead of being told one; see [`Entering`].
pub fn create_ruleset(rung: u32) -> Result<Ruleset, Fail> {
    // A caller asking below the floor means it: the cap flag, driving a
    // measurement. A caller asking at or above it may descend to the floor and
    // no further.
    let bottom = rung.min(vitrin_realm_init::LANDLOCK_MIN_ABI);
    let mut rung = rung;
    loop {
        let attr = RulesetAttr {
            handled_access_fs: handled_access_fs(rung),
            // Deliberately zero; see this module's docs.
            handled_access_net: 0,
            scoped: scoped(rung),
        };
        // SAFETY: `attr` is a live, fully initialized struct and the size
        // passed is this build's own `size_of` for it.
        let rc = unsafe {
            libc::syscall(
                SYS_LANDLOCK_CREATE_RULESET,
                &attr as *const RulesetAttr,
                std::mem::size_of::<RulesetAttr>(),
                0 as libc::c_uint,
            )
        };
        if rc >= 0 {
            return Ok(Ruleset {
                fd: rc as RawFd,
                rung,
            });
        }
        let err = errno();
        // `EINVAL` is a mask bit this kernel does not know; `E2BIG` is a
        // trailing struct field it does not have. Both mean "one rung too
        // high", and both are recoverable by stepping down as far as the floor.
        // Anything else -- `ENOSYS` on a kernel without Landlock, `EPERM` from
        // an LSM above it -- is a refusal, because retrying it would only
        // produce the same answer at every rung.
        if (err == libc::EINVAL || err == libc::E2BIG) && rung > bottom {
            rung -= 1;
            continue;
        }
        return Err(Fail::with(Stage::Landlock, err));
    }
}

/// Grant `rights` on the hierarchy beneath `path`.
///
/// `rights` is masked by the rung's `handled_access_fs` at the call site: a
/// rule naming a bit the ruleset does not handle is `EINVAL`.
///
/// Allocation-free.
pub fn add_path_rule(ruleset: RawFd, path: &CStr, rights: u64) -> Result<(), Fail> {
    if rights == 0 {
        return Ok(());
    }
    // `O_PATH`, so the descriptor is a handle on the name and not on the
    // file's contents: it opens a directory this process may not read, and it
    // does not consume a file description the app could inherit anything
    // from. `O_CLOEXEC` because K13 only *marks* descriptors, and a rule fd
    // that reached the app would be a handle the ruleset does not cover.
    // SAFETY: `path` is a live NUL-terminated string.
    let fd = unsafe { libc::open(path.as_ptr(), libc::O_PATH | libc::O_CLOEXEC) };
    if fd < 0 {
        return Err(Fail::at(Stage::Landlock));
    }
    let attr = PathBeneathAttr {
        allowed_access: rights,
        parent_fd: fd,
    };
    // SAFETY: `attr` is a live packed struct of exactly the kernel's layout.
    let rc = unsafe {
        libc::syscall(
            SYS_LANDLOCK_ADD_RULE,
            ruleset,
            LANDLOCK_RULE_PATH_BENEATH,
            &attr as *const PathBeneathAttr,
            0 as libc::c_uint,
        )
    };
    let err = errno();
    // SAFETY: `fd` is this function's own descriptor and is used nowhere else.
    unsafe { libc::close(fd) };
    if rc < 0 {
        return Err(Fail::with(Stage::Landlock, err));
    }
    Ok(())
}

/// The **ruleset** a caller has committed to entering a Landlock domain with,
/// and the only thing [`restrict_self`] accepts.
///
/// # The published absolute this exists to hold
///
/// `docs/book/src/limits.md` publishes *"No test in this repository enters a
/// Landlock domain at rung 4 or rung 5"*, and the matrix page publishes a
/// per-rung list of the tests that enter one. Until this token existed, the
/// binding between a test and the rungs it enters was `RungsEntered`, which
/// every measurement in `main.rs` **opted into**. An opt-in cannot hold an
/// absolute about tests nobody has written yet: a new test that called
/// `create_ruleset(4)`, then `restrict_self`, and never touched the ledger
/// left that sentence false with `cargo xtask isolation-matrix --check`,
/// `limits-check` and the whole suite green. The generator held
/// declared-name -> real fn, declared-rung -> row and row -> declared rung,
/// and none of those three can see a domain nobody declared.
///
/// So the opt-in is gone. `landlock_restrict_self` is the only syscall that
/// enters a domain, [`restrict_self`] is the only place in this workspace that
/// issues it, and it now demands this token -- which, in a test build, only
/// [`RungsEntered::entering`] can mint. The production mint is compiled
/// **out** of test builds ([`Entering::production`]), so [`apply_with`]'s own
/// path to a domain is not a way around the ledger either; see
/// [`enter_domain`].
///
/// # And it carries the ruleset, not a number beside it
///
/// The first shape of this type held a `u32` the ledger was **told**, and that
/// left the absolute one line short. `entered.entering(1)` beside
/// `create_ruleset(4)` recorded rung 1, entered a rung-4 domain, and every
/// mechanism above stayed green: the ledger compared a number the test typed
/// against a table the same test named, and neither of them was the ruleset.
/// That was not a hypothetical -- the counterexample compiled. Each
/// measurement body papered over it with a line of its own
/// (`let rung = entering.rung();`), which is the remembered discipline this
/// ledger exists to replace.
///
/// It now holds the [`Ruleset`] itself, [`RungsEntered::entering`] reads the
/// rung **off** it, and [`restrict_self`] takes nothing else. The rung recorded
/// and the rung the enforced descriptor was created at are therefore one value
/// rather than two that agree -- there is no argument left for them to disagree
/// in, and the disagreement is now a type error rather than a green run.
///
/// # And it borrows the LEDGER, so the ledger cannot be forgotten under it
///
/// The second shape still left one route open, and it was again found by
/// compiling it rather than by reading. The token borrowed the *ruleset* and
/// nothing else, so this compiled and ran:
///
/// ```ignore
/// let entered = RungsEntered::for_test("a_realm_can_write_where_it_was_granted_and_nowhere_else");
/// let ruleset = create_ruleset(4).expect("a rung-4 ruleset");
/// let entering = entered.entering(&ruleset);
/// std::mem::forget(entered);      // the comparison in `Drop` never runs
/// // ... enter a rung-4 domain with `entering`, and every gate stays green
/// ```
///
/// Two changes close it, and they are load-bearing in different ways:
///
/// - [`RungsEntered::entering`] takes `&'a self` and this token carries a
///   `PhantomData<`[`LedgerBorrow`]`<'a>>`, so the ledger is **borrowed for as
///   long as the token lives**. The `mem::forget` above is now `E0505`,
///   pasted in `docs/book/src/limits.md`.
/// - The comparison against `BEHAVIOURAL_RUNGS` moved **into the mint**, in
///   the direction the published absolute is about. `entering` refuses a rung
///   the test's row does not declare *before* it returns a token, so the
///   sentence "no test enters a domain at rung 4 or rung 5" no longer rests on
///   a destructor at all. What is still in `Drop` is the other direction --
///   rungs a row declares that the run never entered -- and `Drop` is
///   skippable in Rust by construction (`mem::forget`, `ManuallyDrop`,
///   `Box::leak`, `process::exit`, `panic = "abort"`). That residual is
///   published rather than argued away; see `docs/book/src/limits.md`.
///
/// What neither covers is said in the same place: a test that asks the
/// *shipped* helper for a rung never links this module at all (held at
/// `crates/vitrin-core`'s realm spawn, `RUNGS_NO_TEST_ENTERS`), and a test that
/// issues syscall 446 by hand is held by nothing in this file.
#[derive(Clone, Copy)]
pub struct Entering<'a> {
    ruleset: &'a Ruleset,
    /// The ledger's borrow, carried so the type itself says what it holds.
    ///
    /// Zero-sized, and it changes no run. Its whole job is to keep
    /// [`RungsEntered::entering`]'s `&'a self` from being "simplified" back to
    /// `&self` by someone reading this struct and seeing only a ruleset in it.
    ledger: PhantomData<LedgerBorrow<'a>>,
}

/// What [`Entering`] borrows besides the ruleset.
///
/// In a test build that is the ledger; in a shipped build [`RungsEntered`] does
/// not exist, and the production mint has no ledger to borrow.
#[cfg(test)]
type LedgerBorrow<'a> = &'a RungsEntered;
/// See the `cfg(test)` twin: outside a test build there is no ledger.
#[cfg(not(test))]
type LedgerBorrow<'a> = &'a ();

impl<'a> Entering<'a> {
    /// The rung the ruleset about to be entered was **created** at.
    fn rung(self) -> u32 {
        self.ruleset.rung
    }

    /// The production mint, and its `cfg` is the load-bearing half.
    ///
    /// In a test build this function does not exist, so nothing outside
    /// [`RungsEntered`] can produce an [`Entering`] -- which is what makes the
    /// ledger mandatory rather than conventional. It takes the ruleset it is
    /// about to enter, so there is no rung to supply here either.
    #[cfg(not(test))]
    fn production(ruleset: &'a Ruleset) -> Entering<'a> {
        Entering {
            ruleset,
            ledger: PhantomData,
        }
    }
}

/// Every rung a test actually entered a Landlock domain at, recorded as the
/// token is minted and checked against `BEHAVIOURAL_RUNGS` when the ledger
/// drops.
///
/// # Which half is in `Drop`, which half is not, and why the split
///
/// The comparison used to be a method a test called last -- `matches_declaration`
/// at the bottom of four tests, invisible to every gate if a fifth omitted it.
/// That moved into `Drop`, which runs whether a test remembers or not. But
/// `Drop` is not *guaranteed* to run: `mem::forget`, `ManuallyDrop`,
/// `Box::leak`, `process::exit` and `panic = "abort"` each skip it, and the
/// first of those was demonstrated against this very type (see [`Entering`]).
/// A published absolute may not rest on a destructor.
///
/// So the two directions live in two places:
///
/// - **entered ⊆ declared** -- the direction `docs/book/src/limits.md`'s
///   *"No test in this repository enters a Landlock domain at rung 4 or rung 5"*
///   is about -- is asserted in [`RungsEntered::entering`], **before the token
///   exists**. Nothing done to the ledger afterwards can skip it.
/// - **declared ⊆ entered** -- a row claiming a rung the run never entered --
///   is asserted here in `Drop`, and is therefore skippable by the five
///   constructs above. It is a *staleness* check, and the limits page names it
///   as destructor-dependent rather than letting the absolute above cover it.
///
/// The ledger cannot be dropped early under a live token either:
/// [`RungsEntered::entering`] borrows `&'a self`, so `mem::forget(entered)`
/// between the mint and the use is a borrow-check error.
///
/// The ledger is constructed with the test's own name and looks its row up at
/// once, so a typo is a failure at construction rather than a comparison
/// against nothing. Construct it **after** any `skip_unless!`: a skipped test
/// returns before it enters anything, and a ledger dropped with an empty set
/// is a test that declared rungs it did not enter -- which is what this is
/// for.
///
/// The forked measurement bodies do not disturb it: a child reaches `_exit`,
/// which runs no destructor, and the parent's recording happened before the
/// `fork` because the token is minted there.
#[cfg(test)]
pub struct RungsEntered {
    /// The `#[test] fn`'s own name, as `BEHAVIOURAL_RUNGS` spells it.
    test: &'static str,
    /// Every rung handed to [`RungsEntered::entering`], in mint order.
    entered: std::cell::RefCell<Vec<u32>>,
}

#[cfg(test)]
impl RungsEntered {
    /// A ledger for `test`, which `BEHAVIOURAL_RUNGS` must already declare.
    pub fn for_test(test: &'static str) -> RungsEntered {
        assert!(
            crate::tests::BEHAVIOURAL_RUNGS
                .iter()
                .any(|(name, _)| *name == test),
            "{test} opened a Landlock domain ledger and BEHAVIOURAL_RUNGS does not declare it. \
             Add a row: `cargo xtask isolation-matrix` publishes which rungs are exercised, and \
             a test missing from that table is a rung published as measured by nothing"
        );
        RungsEntered {
            test,
            entered: std::cell::RefCell::new(Vec::new()),
        }
    }

    /// Record the rung `ruleset` was **created** at, refuse a rung this test's
    /// row does not declare, and mint the token [`restrict_self`] demands for
    /// that ruleset.
    ///
    /// The rung is read off the ruleset rather than handed in beside it, and
    /// that is the whole difference from the shape this replaced. A ledger that
    /// is *told* a number records what a test said; this one records what the
    /// kernel built. `entering(1)` next to a rung-4 ruleset is no longer a
    /// sentence this API can express.
    ///
    /// # Two things this signature does that a shorter one did not
    ///
    /// **`&'a self`, not `&self`.** The returned token carries the ledger's
    /// borrow ([`Entering::ledger`]), so the ledger cannot be moved -- and
    /// therefore cannot be `mem::forget`ten -- while a token minted from it is
    /// alive. Before that, the counterexample in [`Entering`]'s docs compiled
    /// and ran.
    ///
    /// **The declaration is checked here, not only in [`Drop`].** A destructor
    /// is skippable in Rust by construction, so an absolute that rests on one
    /// is an absolute with a documented hole. This assertion fires *before* the
    /// token exists, so a rung `BEHAVIOURAL_RUNGS` does not declare for this
    /// test cannot reach `landlock_restrict_self` however the ledger is
    /// disposed of afterwards. `Drop` keeps the converse -- a declared rung the
    /// run never entered -- and that half is the one the limits page publishes
    /// as destructor-dependent.
    pub fn entering<'a>(&'a self, ruleset: &'a Ruleset) -> Entering<'a> {
        let rung = ruleset.rung;
        let declared = self.declared();
        assert!(
            declared.contains(&rung),
            "{} is about to enter a Landlock domain at rung {rung}, and BEHAVIOURAL_RUNGS \
             declares {declared:?} for it. That table is what `cargo xtask isolation-matrix` \
             publishes as the rungs each test enters, and `docs/book/src/limits.md` states an \
             absolute about the rungs no test enters at all -- so a rung reached here and \
             missing from the row is a published sentence about to become false. Add the rung \
             to the row if the retarget was intended, and expect the matrix page and the limits \
             page to change with it",
            self.test
        );
        self.entered.borrow_mut().push(rung);
        Entering {
            ruleset,
            ledger: PhantomData,
        }
    }

    /// This ledger's row in `BEHAVIOURAL_RUNGS`.
    ///
    /// [`RungsEntered::for_test`] already refused a name the table does not
    /// carry, so the lookup cannot miss here.
    fn declared(&self) -> &'static [u32] {
        crate::tests::BEHAVIOURAL_RUNGS
            .iter()
            .find(|(name, _)| *name == self.test)
            .expect("checked in `for_test`")
            .1
    }
}

#[cfg(test)]
impl Drop for RungsEntered {
    fn drop(&mut self) {
        // A failing assertion inside the test has already said what is wrong,
        // and a second panic while unwinding aborts the process without
        // printing it.
        if std::thread::panicking() {
            return;
        }
        let mut seen = self.entered.borrow().clone();
        seen.sort_unstable();
        seen.dedup();
        let declared = self.declared();
        // `entering` already refused anything outside `declared`, so what is
        // left for this comparison to catch is a rung the row declares and the
        // run never reached. It is written as an equality anyway: the message
        // is the useful one, and an equality that can only fail one way is
        // cheaper to read than a subset test plus a comment saying why the
        // other direction is impossible.
        assert_eq!(
            seen, declared,
            "{} entered Landlock domains at {seen:?} and BEHAVIOURAL_RUNGS declares \
             {declared:?}. The declaration is what `cargo xtask isolation-matrix` publishes as \
             this test's rungs, so the two have to move together -- update the table if the \
             retarget was intended, and expect the matrix page and `docs/book/src/limits.md` to \
             change with it",
            self.test
        );
    }
}

/// Enter the domain from the **production** path, and refuse to from a test.
///
/// Two bodies. The shipped one mints an [`Entering`] and calls
/// [`restrict_self`]; the `cfg(test)` one panics, because a test that reached
/// this line would have entered a Landlock domain at whatever rung
/// [`apply_with`] planned without passing through [`RungsEntered`] -- the one
/// remaining way around the ledger, and the reason this function exists rather
/// than a bare call. No test drives `apply_with` that far today: the two that
/// call it stop at `--landlock=off` and at a probe answering `ENOSYS`.
#[cfg(not(test))]
fn enter_domain(ruleset: &Ruleset, flags: libc::c_uint) -> Result<(), Fail> {
    restrict_self(Entering::production(ruleset), flags)
}

#[cfg(test)]
fn enter_domain(ruleset: &Ruleset, _flags: libc::c_uint) -> Result<(), Fail> {
    let rung = ruleset.rung();
    panic!(
        "landlock::apply_with reached `landlock_restrict_self` at rung {rung} under `cargo \
         test`. The production path may not enter a Landlock domain in a test build: the rungs \
         a test enters are published per rung on docs/book/src/isolation-matrix.md and as an \
         absolute on docs/book/src/limits.md, and only `RungsEntered` records them. Drive the \
         rung through a forked measurement body with a ledger, or change what those two pages \
         say first."
    )
}

/// Enforce the ruleset on this process and every descendant.
///
/// Requires `PR_SET_NO_NEW_PRIVS`, which K10 has already set. Irreversible by
/// construction: there is no call that removes a Landlock domain.
///
/// The ruleset arrives **inside** `entering` rather than beside it, and that is
/// what makes the recording exact: the descriptor this syscall is handed is the
/// descriptor the ledger was handed, and the rung the ledger wrote down is the
/// rung that descriptor was created at. No caller can reach this syscall
/// without having gone through a mint, and no caller can name a rung here at
/// all; see [`Entering`].
///
/// `flags` is [`restrict_self_flags`]' answer -- zero for every shipped
/// session. It is a parameter rather than a constant read in here so that the
/// forked measurement bodies in `main.rs`'s tests, which drive this function
/// directly, name the flags word they are measuring instead of inheriting one.
///
/// Allocation-free.
pub fn restrict_self(entering: Entering<'_>, flags: libc::c_uint) -> Result<(), Fail> {
    // The rung is not sent to the kernel -- it is already baked into the
    // ruleset -- so this reads it for the one invariant it can state, rather
    // than leaving it unread in a shipped build.
    debug_assert!(
        entering.rung() >= 1,
        "a Landlock domain cannot be entered at rung 0: rung 0 is `--landlock=off`, which builds \
         no ruleset at all"
    );
    // SAFETY: an integer descriptor and a flags word.
    let rc = unsafe { libc::syscall(SYS_LANDLOCK_RESTRICT_SELF, entering.ruleset.fd, flags) };
    if rc < 0 {
        return Err(Fail::at(Stage::Landlock));
    }
    Ok(())
}

